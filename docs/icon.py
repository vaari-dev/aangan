#!/usr/bin/env python3
# Draws Aangan's icon and TV banner: docs/icon.svg and docs/banner.svg, and the Android vector
# drawables res/drawable/icon.xml and banner.xml. Run from the repository root: python3 docs/icon.py
#
# The mark is the nine: eight houses around a sunlit courtyard, which is also a grid of apps with
# one in focus. docs/wordmark.txt holds "Aangan" set in Fraunces (SIL Open Font Licence) at opsz 72,
# wght 520, SOFT 50, as one SVG path in font units (first line: advance, units per em, cap height).
import re
W=open('docs/wordmark.txt').read().split('\n'); adv,upm,cap=map(int,W[0].split()); WORD=W[1]
CHALK=('#F4EDE1','#EBE1D0'); INK='#A9492A'
TONES=['#C8673C','#BC5832','#B04D2C','#A4472A','#963F25']  # lit from the top left

def rr(x,y,w,h,r):
    return f'M{x+r:.2f},{y:.2f}H{x+w-r:.2f}A{r:.2f},{r:.2f} 0 0 1 {x+w:.2f},{y+r:.2f}V{y+h-r:.2f}A{r:.2f},{r:.2f} 0 0 1 {x+w-r:.2f},{y+h:.2f}H{x+r:.2f}A{r:.2f},{r:.2f} 0 0 1 {x:.2f},{y+h-r:.2f}V{y+r:.2f}A{r:.2f},{r:.2f} 0 0 1 {x+r:.2f},{y:.2f}Z'
def circ(cx,cy,r): return f'M{cx-r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2*r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2*r:.2f},0Z'

def mark(ox,oy,s):
    """The nine: eight houses around a lit courtyard. Grid is 62 units at s=1, top-left at ox,oy."""
    cx,cy=ox+31*s,oy+31*s
    # The courtyard's glow spills a little onto the floor between the houses, under them.
    shapes=[('radial',(cx,cy,20*s,[(0.45,'#73F6B544'),(1,'#00F6B544')]),circ(cx,cy,20*s))]
    for row in range(3):
        for col in range(3):
            if row==1 and col==1: continue
            shapes.append(('fill',TONES[row+col],rr(ox+col*22*s,oy+row*22*s,18*s,18*s,4.5*s)))
    shapes.append(('radial',(cx,cy,11*s,[(0,'#FFFFD27A'),(1,'#FFE8962A')]),circ(cx,cy,10.5*s)))
    return shapes

def svg_out(w,h,shapes,clip=None):
    defs=''; body=''
    for i,(k,v,d) in enumerate(shapes):
        if k=='fill': body+=f'<path fill="{v}" d="{d}"/>'
        elif k=='linear':
            (x1,y1,x2,y2,stops)=v
            defs+=f'<linearGradient id="g{i}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">'+''.join(f'<stop offset="{o}" stop-color="#{c[-6:]}" stop-opacity="{int(c[1:3],16)/255 if len(c)==9 else 1:.2f}"/>' for o,c in stops)+'</linearGradient>'
            body+=f'<path fill="url(#g{i})" d="{d}"/>'
        else:
            (cx,cy,r,stops)=v
            defs+=f'<radialGradient id="g{i}" gradientUnits="userSpaceOnUse" cx="{cx:.2f}" cy="{cy:.2f}" r="{r:.2f}">'+''.join(f'<stop offset="{o}" stop-color="#{c[-6:]}" stop-opacity="{int(c[1:3],16)/255 if len(c)==9 else 1:.2f}"/>' for o,c in stops)+'</radialGradient>'
            body+=f'<path fill="url(#g{i})" d="{d}"/>'
    if clip: defs+=f'<clipPath id="c"><path d="{clip}"/></clipPath>'; body=f'<g clip-path="url(#c)">{body}</g>'
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}"><defs>{defs}</defs>{body}</svg>\n'

def argb(c): return c if len(c)==9 else '#FF'+c[1:]
def vd_out(w,h,dpw,dph,shapes,comment,clip=None):
    out=[f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment}\n     Generated by docs/icon.py; edit that, not this. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n    android:width="{dpw}dp"\n    android:height="{dph}dp"\n    android:viewportWidth="{w}"\n    android:viewportHeight="{h}">','    <group>']
    if clip: out.append(f'        <clip-path android:pathData="{clip}" />')
    for k,v,d in shapes:
        if k=='fill': out.append(f'        <path android:fillColor="{argb(v)}" android:pathData="{d}" />'); continue
        if k=='linear':
            x1,y1,x2,y2,stops=v; g=f'android:type="linear" android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}"'
        else:
            cx,cy,r,stops=v; g=f'android:type="radial" android:centerX="{cx:.2f}" android:centerY="{cy:.2f}" android:gradientRadius="{r:.2f}"'
        items=''.join(f'\n                    <item android:offset="{o}" android:color="{argb(c)}" />' for o,c in stops)
        out.append(f'        <path android:pathData="{d}">\n            <aapt:attr name="android:fillColor">\n                <gradient {g}>{items}\n                </gradient>\n            </aapt:attr>\n        </path>')
    out+=['    </group>','</vector>','']
    return '\n'.join(out)

def scale_path(d,s,dx,dy):
    nums=iter(float(n) for n in re.findall(r'-?\d+\.?\d*(?:e-?\d+)?',d))
    out=[]
    for cmd,args in re.findall(r'([MLHVQCZ])([^MLHVQCZ]*)',d):
        a=[float(n) for n in re.findall(r'-?\d+\.?\d*(?:e-?\d+)?',args)]
        if cmd=='H': a=[x*s+dx for x in a]
        elif cmd=='V': a=[y*s+dy for y in a]
        else: a=[(v*s+dx) if i%2==0 else (v*s+dy) for i,v in enumerate(a)]
        out.append(cmd+' '.join(f'{v:.2f}' for v in a))
    return ''.join(out)

bg=lambda w,h:('linear',(0,0,0,h,[(0,'#FF'+CHALK[0][1:]),(1,'#FF'+CHALK[1][1:])]),f'M0,0H{w}V{h}H0Z')
# Icon: 100x100, rounded like the TV's own tiles.
icon=[bg(100,100)]+mark(19,19,1)
iclip=rr(0,0,100,100,22)
# Banner: 160x90, the mark at left and the name beside it.
gs=36/62; s=0.01356
gx,gy=11.5,27; tx=gx+62*gs+9; base=45+cap*s/2
banner=[bg(160,90)]+mark(gx,gy,gs)+[('fill',INK,scale_path(WORD,s,tx,base))]
open('docs/icon.svg','w').write(svg_out(100,100,icon,iclip))
open('docs/banner.svg','w').write(svg_out(160,90,banner))
open('assets/phone/mark.svg','w').write(svg_out(100,100,icon,iclip))
open('res/drawable/icon.xml','w').write(vd_out(100,100,96,96,icon,"Aangan's icon: eight houses around a sunlit courtyard, which is also a grid of apps with one in focus.",iclip))
open('res/drawable/banner.xml','w').write(vd_out(160,90,320,180,banner,"Aangan's TV banner: the icon's nine, and the name set in Fraunces (SIL Open Font Licence), drawn as paths."))
